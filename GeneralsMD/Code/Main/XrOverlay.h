// GeneralsX @feature Codex 13/09/2026 Small, attached control legend; never covers game UI.
#pragma once
#include <array>
#include <string>
#include <vector>

static constexpr int kLegendWidth=1024, kLegendHeight=104;
static std::vector<unsigned char> xrLegendPixels(const std::array<std::string,3> &lines, bool arranging)
{
	// Original compact 5-column bitmap glyphs, bit 0 is the top row.
	static const unsigned char glyphs[][5]={
		{0x3e,0x51,0x49,0x45,0x3e},{0,0x42,0x7f,0x40,0},{0x62,0x51,0x49,0x49,0x46},
		{0x22,0x41,0x49,0x49,0x36},{0x18,0x14,0x12,0x7f,0x10},{0x27,0x45,0x45,0x45,0x39},
		{0x3c,0x4a,0x49,0x49,0x30},{1,0x71,9,5,3},{0x36,0x49,0x49,0x49,0x36},{6,0x49,0x49,0x29,0x1e},
		{0x7e,9,9,9,0x7e},{0x7f,0x49,0x49,0x49,0x36},{0x3e,0x41,0x41,0x41,0x22},
		{0x7f,0x41,0x41,0x22,0x1c},{0x7f,0x49,0x49,0x49,0x41},{0x7f,9,9,9,1},
		{0x3e,0x41,0x49,0x49,0x7a},{0x7f,8,8,8,0x7f},{0,0x41,0x7f,0x41,0},
		{0x20,0x40,0x40,0x40,0x3f},{0x7f,8,0x14,0x22,0x41},{0x7f,0x40,0x40,0x40,0x40},
		{0x7f,2,0x0c,2,0x7f},{0x7f,2,4,8,0x7f},{0x3e,0x41,0x41,0x41,0x3e},
		{0x7f,9,9,9,6},{0x3e,0x41,0x51,0x21,0x5e},{0x7f,9,0x19,0x29,0x46},
		{0x46,0x49,0x49,0x49,0x31},{1,1,0x7f,1,1},{0x3f,0x40,0x40,0x40,0x3f},
		{0x1f,0x20,0x40,0x20,0x1f},{0x3f,0x40,0x38,0x40,0x3f},{0x63,0x14,8,0x14,0x63},
		{7,8,0x70,8,7},{0x61,0x51,0x49,0x45,0x43},
		{0,0,0x60,0,0},{0x40,0x20,0x10,8,4},{8,8,8,8,8},{8,8,0x3e,8,8},{0,0,0x7f,0,0}
	};
	std::vector<unsigned char> pixels(kLegendWidth*kLegendHeight*4);
	for(int y=0;y<kLegendHeight;++y) for(int x=0;x<kLegendWidth;++x) {
		const int p=(y*kLegendWidth+x)*4;
		pixels[p]=12;pixels[p+1]=20;pixels[p+2]=28;pixels[p+3]=255;
	}
	for(int line=0;line<3;++line) for(size_t c=0;c<lines[line].size() && c<55;++c) {
		const char ch=lines[line][c];
		const int g=ch>='0' && ch<='9' ? ch-'0' : ch>='A' && ch<='Z' ? ch-'A'+10 :
			ch=='.'?36:ch=='/'?37:ch=='-'?38:ch=='+'?39:ch=='|'?40:-1;
		if(g<0) continue;
		for(int col=0;col<5;++col) for(int row=0;row<7;++row) if(glyphs[g][col]&(1<<row))
			for(int dy=0;dy<3;++dy) for(int dx=0;dx<3;++dx) {
				const int x=12+int(c)*18+col*3+dx, y=kLegendHeight-1-(8+line*32+row*3+dy);
				const int p=(y*kLegendWidth+x)*4;
				pixels[p]=line==0 ? (arranging ? 255:80):225;
				pixels[p+1]=line==0 ? (arranging ? 190:220):235;
				pixels[p+2]=line==0 ? (arranging ? 60:255):242;
			}
	}
	return pixels;
}
